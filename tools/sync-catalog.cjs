const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const CATALOG_FILE = path.join(ROOT, 'scenes.json');
const GENERATED_FILE = path.join(ROOT, 'scenes.generated.js');
const INDEX_FILE = path.join(ROOT, 'index.html');
const README_FILE = path.join(ROOT, 'README.md');
const README_START = '<!-- BEGIN GENERATED SCENE TABLE -->';
const README_END = '<!-- END GENERATED SCENE TABLE -->';
const SITE_BASE = 'https://ptsfdtz.github.io/711-night/';

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, character => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;'
  })[character]);
}

function loadCatalog() {
  const scenes = JSON.parse(fs.readFileSync(CATALOG_FILE, 'utf8'));
  assert(Array.isArray(scenes) && scenes.length > 0, 'scenes.json must contain a non-empty array.');

  const seenDirectories = new Set();
  scenes.forEach((scene, index) => {
    const label = `scenes.json entry ${index + 1}`;
    assert(scene && typeof scene === 'object' && !Array.isArray(scene), `${label} must be an object.`);
    assert(typeof scene.name === 'string' && scene.name.trim(), `${label} needs a non-empty name.`);
    assert(typeof scene.dir === 'string' && scene.dir.trim(), `${label} needs a non-empty dir.`);
    assert(!/[\\/]/.test(scene.dir) && scene.dir !== '.' && scene.dir !== '..', `${label} dir must be a single directory name.`);

    const normalizedDir = scene.dir.toLowerCase();
    assert(!seenDirectories.has(normalizedDir), `${label} duplicates directory "${scene.dir}".`);
    seenDirectories.add(normalizedDir);

    if (scene.entry !== undefined) {
      assert(typeof scene.entry === 'string' && scene.entry.trim(), `${label} entry must be a non-empty relative path.`);
      const entrySegments = scene.entry.split(/[\\/]/);
      assert(!path.isAbsolute(scene.entry) && !entrySegments.includes('..'), `${label} entry must stay inside its scene directory.`);
    }
    if (scene.note !== undefined) {
      assert(typeof scene.note === 'string' && scene.note.trim(), `${label} note must be a non-empty string.`);
    }

    const sceneRoot = path.resolve(ROOT, scene.dir);
    const entryPath = path.resolve(sceneRoot, scene.entry || 'index.html');
    const relativeEntry = path.relative(sceneRoot, entryPath);
    assert(relativeEntry && !relativeEntry.startsWith(`..${path.sep}`) && relativeEntry !== '..' && !path.isAbsolute(relativeEntry), `${label} entry resolves outside its scene directory.`);
    assert(fs.existsSync(entryPath) && fs.statSync(entryPath).isFile(), `${label} entry does not exist: ${path.relative(ROOT, entryPath)}.`);
  });

  return scenes;
}

function renderGeneratedScript(scenes) {
  return `// Generated by tools/sync-catalog.cjs from scenes.json. Do not edit directly.\nwindow.SCENES = ${JSON.stringify(scenes, null, 2)};\n`;
}

function renderIndex(index, scenes) {
  const version = crypto.createHash('sha256').update(JSON.stringify(scenes)).digest('hex').slice(0, 12);
  const scriptTags = index.match(/<script src="scenes\.generated\.js(?:\?v=[a-f0-9]{12})?"><\/script>/g) || [];
  const versionedTag = `<script src="scenes.generated.js?v=${version}"></script>`;
  assert(scriptTags.length === 1, 'index.html must include one scenes.generated.js script tag.');
  return index.replace(scriptTags[0], versionedTag);
}

function renderCell(scene) {
  const entryPath = scene.entry ? `/${scene.entry.split('/').map(encodeURIComponent).join('/')}` : '/';
  const href = `${SITE_BASE}${encodeURIComponent(scene.dir)}${entryPath}`;
  const preview = `docs/previews/${scene.dir.toLowerCase()}.png`;
  const name = escapeHtml(scene.name);
  const note = scene.note ? `<br>\n      <small>${escapeHtml(scene.note)}。</small>` : '';

  return `    <td width="50%" valign="top">\n      <a href="${escapeHtml(href)}"><img src="${escapeHtml(preview)}" alt="${name} 生成的雨夜便利店场景预览"></a><br>\n      <b>${name}</b> · <a href="${escapeHtml(href)}">打开互动场景</a>${note}\n    </td>`;
}

function renderReadmeTable(scenes) {
  const rows = [];
  for (let index = 0; index < scenes.length; index += 2) {
    const left = renderCell(scenes[index]);
    const right = scenes[index + 1] ? renderCell(scenes[index + 1]) : '    <td width="50%" valign="top"></td>';
    rows.push(`  <tr>\n${left}\n${right}\n  </tr>`);
  }
  return `<table>\n${rows.join('\n')}\n</table>`;
}

function replaceReadmeTable(readme, table) {
  const startIndex = readme.indexOf(README_START);
  const endIndex = readme.indexOf(README_END);
  assert(startIndex >= 0 && endIndex > startIndex, 'README.md is missing generated table markers.');
  assert(readme.indexOf(README_START, startIndex + README_START.length) < 0, 'README.md has duplicate start markers.');
  assert(readme.indexOf(README_END, endIndex + README_END.length) < 0, 'README.md has duplicate end markers.');

  const contentStart = startIndex + README_START.length;
  return `${readme.slice(0, contentStart)}\n${table}\n${readme.slice(endIndex)}`;
}

function writeIfChanged(file, expected) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === expected) return false;
  fs.writeFileSync(file, expected, 'utf8');
  return true;
}

function main() {
  const args = process.argv.slice(2);
  assert(args.length <= 1 && (args.length === 0 || args[0] === '--check'), 'Usage: node tools/sync-catalog.cjs [--check]');
  const checkOnly = args[0] === '--check';
  const scenes = loadCatalog();
  const generatedScript = renderGeneratedScript(scenes);
  const index = fs.readFileSync(INDEX_FILE, 'utf8');
  const generatedIndex = renderIndex(index, scenes);
  const readme = fs.readFileSync(README_FILE, 'utf8');
  const generatedReadme = replaceReadmeTable(readme, renderReadmeTable(scenes));
  const outputs = [[GENERATED_FILE, generatedScript], [INDEX_FILE, generatedIndex], [README_FILE, generatedReadme]];

  if (checkOnly) {
    const stale = outputs.filter(([file, expected]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== expected);
    if (stale.length) {
      throw new Error(`Generated catalog files are out of date: ${stale.map(([file]) => path.relative(ROOT, file)).join(', ')}. Run node tools/sync-catalog.cjs.`);
    }
    console.log(`Catalog is valid and generated files are current (${scenes.length} scenes).`);
    return;
  }

  const changed = outputs.filter(([file, expected]) => writeIfChanged(file, expected)).map(([file]) => path.relative(ROOT, file));
  console.log(changed.length ? `Updated ${changed.join(', ')} (${scenes.length} scenes).` : `Catalog is already synchronized (${scenes.length} scenes).`);
}

try {
  main();
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
